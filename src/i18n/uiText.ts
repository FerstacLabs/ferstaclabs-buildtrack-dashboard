export const translateUiText = (text: string, language: AppLanguage) => {
  const trimmed = text.trim()
  if (!trimmed) return text

  const exact = exactTranslate(trimmed, language)
  if (exact) return text.replace(trimmed, exact)

  const duration = translateDuration(trimmed, language)
  if (duration) return text.replace(trimmed, duration)

  const prefix = prefixTranslations.find((entry) => trimmed.startsWith(entry.prefix))
  if (prefix) return text.replace(prefix.prefix, prefix.translations[language])

  const eventCount = /^(\d+)\s+hadisə$/.exec(trimmed)
  if (eventCount) {
    const translated = language === 'en' ? `${eventCount[1]} events` : language === 'ru' ? `${eventCount[1]} событий` : trimmed
    return text.replace(trimmed, translated)
  }

  return text
}

