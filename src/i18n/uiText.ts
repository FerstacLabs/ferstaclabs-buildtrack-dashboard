const exactTranslate = (text: string, language: AppLanguage) => uiTextTranslations[text]?.[language]

const translateDuration = (text: string, language: AppLanguage) => {
  const hourMinute = /^(\d+)\s+saat\s+(\d+)\s+dəq$/.exec(text)
  if (hourMinute) {
    if (language === 'en') return `${hourMinute[1]} h ${hourMinute[2]} min`
    if (language === 'ru') return `${hourMinute[1]} ч ${hourMinute[2]} мин`
  }

  const minutes = /^(\d+)\s+dəq$/.exec(text)
  if (minutes) {
    if (language === 'en') return `${minutes[1]} min`
    if (language === 'ru') return `${minutes[1]} мин`
  }

  const perDay = /^(.+)\/gün$/.exec(text)
  if (perDay) {
    if (language === 'en') return `${perDay[1]}/day`
    if (language === 'ru') return `${perDay[1]}/день`
  }

  const perHour = /^(.+)\/saat$/.exec(text)
  if (perHour) {
    if (language === 'en') return `${perHour[1]}/hour`
    if (language === 'ru') return `${perHour[1]}/час`
  }

  return undefined
}

